"""make_results_table.py - LaTeX results table straight from runs_table.csv.

    python make_results_table.py 10x10=<report>/runs_table.csv 15x15=... \
        [--out results_table.tex]

Emits a booktabs table* with one row per (map, mode, planner): kept-run count,
genuine (+assisted) successes, and success-only means +/- sd for mission time,
executed path length, turn count, net energy, plus mean planner inference.
Generated from the measured data so the report numbers cannot drift from it.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from day_aggregate import MODE_ORDER, PLANNER_ORDER  # noqa: E402

PLANNER_TEX = {"astar_shortest": "shortest-A\\textsuperscript{*}",
               "astar_energy": "energy-A\\textsuperscript{*}",
               "ppo": "PPO"}

HEADER = r"""% Auto-generated by analysis/make_results_table.py -- do not edit by hand.
\begin{table*}[t]
\centering
\caption{Measured outcomes per (map, mode, planner). Success counts genuine
(goal reached unaided); PPO's assisted finishes in parentheses. Time, path,
turns and net energy are mean$\pm$sd over \emph{successful} runs (incl.\
assisted); inference is the mean over all kept runs.}
\label{tab:fullresults}
\footnotesize
\setlength{\tabcolsep}{4.5pt}
\begin{tabular}{@{}llrlrrrrr@{}}
\toprule
\textbf{Map} & \textbf{Mode / planner} & $n$ & \textbf{Success} &
\textbf{Time (s)} & \textbf{Path (m)} & \textbf{Turns} &
\textbf{Net energy (mWh)} & \textbf{Inference (ms)}\\
\midrule"""

FOOTER = r"""\bottomrule
\end{tabular}
\end{table*}"""


def _ms(vals: pd.Series, digits: int = 1) -> str:
    vals = pd.to_numeric(vals, errors="coerce").dropna()
    if not len(vals):
        return "--"
    return f"${vals.mean():.{digits}f}\\pm{vals.std():.{digits}f}$"


def rows_for(label: str, df: pd.DataFrame) -> list[str]:
    out = []
    first = True
    for mode in MODE_ORDER:
        for planner in PLANNER_ORDER:
            sub = df[(df["mode"] == mode) & (df["planner"] == planner)]
            if not len(sub):
                continue
            ok = sub[sub["success"]]
            genuine = int(sub["genuine_success"].sum())
            assisted = int(sub["assisted_success"].sum())
            succ = f"{genuine}/{len(sub)}" + (f" (+{assisted})" if assisted else "")
            inf_ms = pd.to_numeric(sub["planner_inference_mean_us"],
                                   errors="coerce").dropna() / 1000.0
            map_cell = (f"\\multirow{{{6}}}{{*}}{{${label}$}}" if first else "")
            first = False
            out.append(
                f"{map_cell} & {mode[:3]}.\\ / {PLANNER_TEX[planner]} & {len(sub)} & {succ} & "
                f"{_ms(ok['time_to_completion_s'])} & {_ms(ok['executed_path_length_m'], 2)} & "
                f"{_ms(ok['turn_count'])} & {_ms(ok['energy_net_mwh'])} & "
                f"${inf_ms.mean():.2f}$\\\\"
            )
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("tables", nargs="+", help="label=path/to/runs_table.csv")
    ap.add_argument("--out", type=Path, default=Path("results_table.tex"))
    args = ap.parse_args(argv)

    lines = [HEADER]
    for i, arg in enumerate(args.tables):
        label, path = arg.split("=", 1)
        df = pd.read_csv(path)
        if i:
            lines.append("\\midrule")
        lines.extend(rows_for(label.replace("x", "\\times"), df))
    lines.append(FOOTER)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print("wrote", args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
